"""Verified OpenAI Whisper large-v3 weights converted locally for MLX.

Uses the weight layout documented by Apple's mlx-examples/whisper converter
and the download URL/checksum published by openai/whisper. No third-party mirror.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import sys
import urllib.request

from .storage import file_hash, write_json

SHA256 = "e5b1a55b89c1367dacf97e3e19bfd829a01529dbfdeefa8caeb59b3f1b81dadb"
URL = f"https://openaipublic.azureedge.net/main/whisper/models/{SHA256}/large-v3.pt"
ALIGNMENT_HEADS = b"ABzY8gWO1E0{>%R7(9S+Kn!D~%ngiGaR?*L!iJG9p-nab0JQ=-{D1-g00"


def prepare_large_v3(state: Path) -> Path:
    target = state / "models/whisper-large-v3-mlx"
    marker = target / "provenance.json"
    if marker.exists() and (target / "weights.safetensors").exists() and (target / "config.json").exists():
        from .storage import read_json
        meta = read_json(marker)
        if (meta.get("source_sha256") == SHA256 and
                file_hash(target / "weights.safetensors") == meta.get("converted_sha256")):
            return target
    cache = state / "downloads"
    cache.mkdir(exist_ok=True)
    checkpoint_path = cache / "large-v3.pt"
    if not checkpoint_path.exists() or file_hash(checkpoint_path) != SHA256:
        partial = checkpoint_path.with_suffix(".partial")
        print("Downloading official Whisper large-v3 weights (about 3.1 GB)...", file=sys.stderr, flush=True)
        with urllib.request.urlopen(URL, timeout=120) as response, partial.open("wb") as output:
            while block := response.read(4 * 1024 * 1024):
                output.write(block)
        if file_hash(partial) != SHA256:
            raise ValueError("Official checkpoint checksum mismatch; refusing to load it")
        os.replace(partial, checkpoint_path)
    import mlx.core as mx
    from mlx.utils import tree_flatten
    from mlx_whisper.whisper import ModelDimensions, Whisper
    import torch

    print("Converting verified weights to MLX float16...", file=sys.stderr, flush=True)
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    weights = []
    for name, tensor in checkpoint["model_state_dict"].items():
        if name == "encoder.positional_embedding":
            continue
        name = name.replace("mlp.0", "mlp1").replace("mlp.2", "mlp2")
        array = tensor.detach().numpy()
        if "conv" in name and array.ndim == 3:
            array = array.swapaxes(1, 2)
        weights.append((name, mx.array(array).astype(mx.float16)))
    model = Whisper(ModelDimensions(**checkpoint["dims"]), mx.float16)
    # The encoder's sinusoidal positional embedding is generated by MLX.
    model.load_weights(weights, strict=False)
    model.set_alignment_heads(ALIGNMENT_HEADS)
    target.mkdir(parents=True, exist_ok=True)
    temporary = target / "weights.partial.safetensors"
    mx.save_safetensors(str(temporary), dict(tree_flatten(model.parameters())))
    os.replace(temporary, target / "weights.safetensors")
    write_json(target / "config.json", checkpoint["dims"])
    write_json(marker, {"source": URL, "source_sha256": SHA256, "dtype": "float16",
                       "converted_sha256": file_hash(target / "weights.safetensors")})
    return target
